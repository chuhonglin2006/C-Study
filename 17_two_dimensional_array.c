#include <stdio.h>

/// 二维数组

// 二维数组可以理解为一个表格,第一个下标是行,第二个下标是列

int main() {
    // 定义一个二维数组
    int two_arr[2][3] = { // 2表示二维数组里面能放两个数组 3表示里面每个数组可以放3个元素
        {1,2,3},
        {4,5,6}
    };

    // 遍历二维数组
    for (int i = 0;i < 2;i++) { //行
        for (int j = 0;j < 3;j++) { // 列
            printf("%d ",two_arr[i][j]);
        }
    }
    return 0;
}

/* 数组的几个不能:
 * 1.不能整体赋值 只能使用循环逐个复制
 * 2.不能整体比较 比较的是内存地址
 * 3.数组长度必须在定义时确定,不能使用 运行时才知道的变量 做为长度
 */