// arr是数组名 5是长度(最多能存5个int) 元素下表从0开始

// 初始化的几种写法
int a[5] = {1,2,3,4,5}; // 完整初始化
int b[5] = {1,2}; // 前两个为2其余自动补0
int c[5] = {0}; // 全部初始化为0
