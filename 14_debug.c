#include <stdio.h>

/// 调试C代码

// 调试器:能让程序暂停在指定的位置然后一步一步的执行 让你看到每个变量的值
// 断点:告诉调试器 运行到这里就停下
// 单步执行:暂停后 一次只执行一行或进入一个函数
// 观察变量:暂停时查看各个变量的值

int add(int x, int y) {
    int r = x + y;
    return r;
}

int main() {
    int a = add(1, 2);
    printf("%d", a);
    return 0;
}


/* 操作步骤:
 * 1.设置断点:点击代码旁边空白处
 * 2.以调试模式启动
 * 3.观察
 * */